import sharp from 'sharp';
import { writeFile, unlink } from 'node:fs/promises';

const root = 'public/landing/hero/';
const { data, info } = await sharp(root + 'tv-slot.png').ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const bounds = { screen: [info.width, info.height, 0, 0], slot: [info.width, info.height, 0, 0] };
for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
  const i = (y * info.width + x) * 4;
  const [r, g, b] = data.subarray(i, i + 3);
  const kind = g > 150 && g > r * 1.8 && g > b * 1.8 ? 'screen' : r > 130 && b > 130 && g < 80 ? 'slot' : null;
  if (!kind) continue;
  const box = bounds[kind];
  box[0] = Math.min(box[0], x); box[1] = Math.min(box[1], y);
  box[2] = Math.max(box[2], x); box[3] = Math.max(box[3], y);
  if (kind === 'slot') data[i] = data[i + 1] = data[i + 2] = 20;
}
// Remove chroma spill on the glass edge and inside the dark slot bezel.
for (let i = 0; i < data.length; i += 4) {
  const [r, g, b] = data.subarray(i, i + 3);
  if (g > r * 1.15 && g > b * 1.15) data[i + 1] = Math.round((r + b) / 2);
  if (r > g * 1.6 && b > g * 1.6 && b > r * .65) {
    data[i] = data[i + 1] = data[i + 2] = Math.round(g);
  }
}
// Flood-fill only the light backdrop connected to the image perimeter.
// This leaves the wood, controls, glass and darker contact shadow intact.
const visited = new Uint8Array(info.width * info.height);
const queue = [];
const enqueue = pixel => {
  if (visited[pixel]) return;
  visited[pixel] = 1;
  const i = pixel * 4;
  const channels = [data[i], data[i + 1], data[i + 2]];
  if (Math.min(...channels) < 205 || Math.max(...channels) - Math.min(...channels) > 32) return;
  queue.push(pixel);
};
for (let x = 0; x < info.width; x++) { enqueue(x); enqueue((info.height - 1) * info.width + x); }
for (let y = 0; y < info.height; y++) { enqueue(y * info.width); enqueue(y * info.width + info.width - 1); }
for (let cursor = 0; cursor < queue.length; cursor++) {
  const pixel = queue[cursor], x = pixel % info.width, y = Math.floor(pixel / info.width);
  const i = pixel * 4;
  data[i] = data[i + 1] = data[i + 2] = 255;
  if (x > 0) enqueue(pixel - 1);
  if (x < info.width - 1) enqueue(pixel + 1);
  if (y > 0) enqueue(pixel - info.width);
  if (y < info.height - 1) enqueue(pixel + info.width);
}
await sharp(data, { raw: info }).webp({ quality: 90 }).toFile(root + 'tv-white.webp');
const geometry = Object.fromEntries(Object.entries(bounds).map(([key, [x, y, right, bottom]]) => [key, {
  left: x / info.width * 100, top: y / info.height * 100,
  width: (right - x + 1) / info.width * 100, height: (bottom - y + 1) / info.height * 100,
}]));
await writeFile('features/root/home/hero-retro-geometry.ts', `// Generated by scripts/optimize-hero-assets.mjs\nexport const retroGeometry = ${JSON.stringify(geometry, null, 2)} as const;\n`);
const meta = await sharp(root + 'photostrip.png').metadata();
await sharp(root + 'photostrip.png').extract({ left: Math.round(meta.width * .238), top: Math.round(meta.height * .036), width: Math.round(meta.width * .526), height: Math.round(meta.height * .926) }).webp({ quality: 88 }).toFile(root + 'photostrip.webp');
console.log('Hero assets optimized.');
for (const file of ['tv.png', 'printer.png', 'printer.webp']) await unlink(root + file).catch(error => { if (error.code !== 'ENOENT') throw error; });
